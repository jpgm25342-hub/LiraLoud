let currentLanguage = "es";

function toggleIdiomaDrop(nuevoIdioma) {
    currentLanguage = nuevoIdioma;
    applyTranslations();
    if (typeof guardarTodosAjustes === 'function') guardarTodosAjustes();
}

function toggleIdioma() {
    currentLanguage = currentLanguage === "es" ? "en" : "es";
    applyTranslations();
}

function applyTranslations() {
    const dict = translations[currentLanguage];
    
    // Función ayudante para cambiar texto de un elemento si existe
    const setText = (id, key) => {
        const el = document.getElementById(id);
        if (el && dict[key]) el.innerText = dict[key];
    };

    // Se han removido las llamadas a setText para los botones principales
    // ya que ahora utilizan spans con data-i18n para no borrar los íconos SVG.
    
    setText("opcion-leer", "menu-leer");
    setText("opcion-copiar", "menu-copiar");
    setText("opcion-buscar", "menu-buscar");
    
    // Algunos son headers
    const carga = document.querySelector("#pantalla-carga h2");
    if(carga && dict["carga-titulo"]) carga.innerText = dict["carga-titulo"];
    
    // Nueva lógica: Buscar todos los elementos con data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            el.innerHTML = dict[key]; // usamos innerHTML por si tienen emojis
        }
    });

    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
        const key = el.getAttribute('data-i18n-ph');
        if (dict[key]) {
            el.setAttribute('placeholder', dict[key]);
        }
    });

    // Tarea 6: Actualizar atajos dinámicos en tiempo real
    if (typeof renderizarAtajos === 'function') {
        renderizarAtajos();
    }
}

function translateDynamicText(key) {
    return translations[currentLanguage][key] || key;
}

window.translateDynamicText = translateDynamicText;
window.toggleIdioma = toggleIdioma;
window.toggleIdiomaDrop = toggleIdiomaDrop;
window.applyTranslations = applyTranslations;

// Tarea 3: Modo Oscuro UI y PDF
function toggleDarkMode(forzarActivo = null, guardar = true) {
    // 1. Oscurecer la Interfaz (UI)
    if (forzarActivo !== null) {
        if (forzarActivo) {
            document.body.classList.add("ui-dark-mode");
        } else {
            document.body.classList.remove("ui-dark-mode");
        }
    } else {
        document.body.classList.toggle("ui-dark-mode");
    }

    // 2. Oscurecer el lienzo del PDF
    const canvas = document.getElementById("lienzo-pdf");
    if(canvas) {
        if (forzarActivo !== null) {
            if (forzarActivo) canvas.classList.add("canvas-dark-mode");
            else canvas.classList.remove("canvas-dark-mode");
        } else {
            canvas.classList.toggle("canvas-dark-mode");
        }
    }
    
    // 3. Guardar ajuste en persistencia
    if (guardar && typeof guardarTodosAjustes === 'function') {
        guardarTodosAjustes();
    }
}
window.toggleDarkMode = toggleDarkMode;
